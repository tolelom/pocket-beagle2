#!/bin/bash
# PocketBeagle 2 — 1b: R5 패스 빌드
#
# 산출물: out/r5/tiboot3.bin       (순정, SD 부팅용)
#         out/r5-dfu/tiboot3.bin   (DFU 이어받기용, 스토리지 부팅 불가)
#
# 두 빌드가 다른 이유: SPL 하나에 스토리지 부팅과 DFU를 모두 넣으면 크기가
# 넘쳐서, am62x_r5_usbdfu.config 가 스토리지 지원을 끄고 DFU 를 켠다.
# (doc/board/ti/am62x_sk.rst 3.1.1)
set -u

# 저장소 위치를 홈에 묶지 않는다. 집(WSL)과 회사(Ubuntu)의 홈 경로가 달라도
# 스크립트가 놓인 자리를 작업 루트로 잡으면 양쪽에서 그대로 돈다.
WS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UB="$WS/u-boot"
FW="$WS/ti-linux-firmware"
VENV="$WS/venv"

# binman 이 요구하는 정확한 파이썬 패키지 버전 (tools/binman/requirements.txt)
# shellcheck disable=SC1091
. "$VENV/bin/activate" || { echo "venv 없음: $VENV"; exit 1; }

export CROSS_COMPILE=arm-linux-gnueabihf-
J=$(nproc)

build() {
    local out="$1"; shift
    local cfgs="$*"
    echo
    echo "############################################################"
    echo "# BUILD: $out   [$cfgs]"
    echo "############################################################"
    rm -rf "${WS:?}/out/$out"
    mkdir -p "$WS/out/$out"

    if ! make -C "$UB" O="$WS/out/$out" $cfgs > "$WS/out/$out.cfg.log" 2>&1; then
        echo "!!! defconfig 실패:"; tail -20 "$WS/out/$out.cfg.log"; return 1
    fi
    echo "defconfig OK"

    make -C "$UB" O="$WS/out/$out" BINMAN_INDIRS="$FW" -j"$J" \
        > "$WS/out/$out.build.log" 2>&1
    local rc=$?
    echo "make exit: $rc"
    if [ $rc -ne 0 ]; then
        echo "!!! 빌드 실패, 마지막 30줄:"; tail -30 "$WS/out/$out.build.log"; return 1
    fi

    echo "--- 산출물:"
    ls -l "$WS/out/$out"/tiboot3* "$WS/out/$out"/spl/u-boot-spl.bin 2>/dev/null
    return 0
}

build r5     am62_pocketbeagle2_r5_defconfig      ; RC1=$?
build r5-dfu am62_pocketbeagle2_r5_defconfig am62x_r5_usbdfu.config ; RC2=$?

echo
echo "############################################################"
echo "# 결과:  r5(순정) rc=$RC1    r5-dfu rc=$RC2"
echo "############################################################"
echo
echo "=== tiboot3 전체 (문서 기록 보드 원본: 282,506 바이트) ==="
find "$WS/out" -name 'tiboot3*' -printf '%10s  %p\n' 2>/dev/null | sort -k2

echo
echo "=== SPL 빌드 타임스탬프 (1단계 완료 기준: 콘솔 배너가 이 값이어야 한다) ==="
for d in r5 r5-dfu; do
    v="$WS/out/$d/include/generated/timestamp_autogenerated.h"
    [ -f "$v" ] && { echo "[$d]"; grep -E 'U_BOOT_(DATE|TIME)' "$v" | sed 's/^/  /'; }
done

echo
echo "=== U-Boot 버전 문자열 ==="
for d in r5 r5-dfu; do
    v="$WS/out/$d/include/generated/version_autogenerated.h"
    [ -f "$v" ] && echo "[$d] $(grep PLAIN_VERSION "$v")"
done
